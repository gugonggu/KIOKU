begin;

create unique index itinerary_items_trip_memory_link on public.itinerary_items(trip_id,id);

create table public.trip_memory_entries (
  id uuid primary key,
  trip_id uuid not null references public.trips(id) on delete cascade,
  day date not null check (day between date '0001-01-01' and date '9999-12-31'),
  title text not null check (char_length(title) <= 100 and title ~ '[^[:space:]]'),
  body text not null check (char_length(body) <= 4000 and body ~ '[^[:space:]]'),
  place_id uuid,
  schedule_id uuid,
  created_at timestamptz not null default now(),
  unique (trip_id,id),
  foreign key (trip_id,place_id) references public.trip_places(trip_id,id) on delete set null (place_id),
  foreign key (trip_id,schedule_id) references public.itinerary_items(trip_id,id) on delete set null (schedule_id)
);
create index trip_memory_entries_date on public.trip_memory_entries(trip_id,day,created_at,id);

create table public.trip_memory_photos (
  id uuid primary key,
  trip_id uuid not null references public.trips(id) on delete restrict,
  day date not null check (day between date '0001-01-01' and date '9999-12-31'),
  title text not null check (char_length(title) <= 100 and title ~ '[^[:space:]]'),
  caption text check (char_length(caption) <= 500),
  entry_id uuid,
  place_id uuid,
  phase text not null default 'pending' check (phase in ('pending','ready','deleting')),
  width integer check (width between 1 and 1440),
  height integer check (height between 1 and 1440),
  bytes integer check (bytes between 1 and 524288),
  is_cover boolean not null default false,
  sort_order bigint generated by default as identity,
  created_at timestamptz not null default now(),
  check (phase <> 'ready' or (width is not null and height is not null and bytes is not null)),
  check (not is_cover or phase = 'ready'),
  foreign key (trip_id,entry_id) references public.trip_memory_entries(trip_id,id) on delete set null (entry_id),
  foreign key (trip_id,place_id) references public.trip_places(trip_id,id) on delete set null (place_id)
);
create unique index trip_memory_one_cover on public.trip_memory_photos(trip_id) where is_cover;
create index trip_memory_photos_order on public.trip_memory_photos(trip_id,sort_order,id);

create table public.trip_visit_marks (
  trip_id uuid not null,
  schedule_id uuid not null,
  status text not null check (status in ('planned','visited','missed')),
  primary key (trip_id,schedule_id),
  foreign key (trip_id,schedule_id) references public.itinerary_items(trip_id,id) on delete cascade
);

alter table public.trip_memory_entries enable row level security;
alter table public.trip_memory_photos enable row level security;
alter table public.trip_visit_marks enable row level security;

create policy memory_entries_owner on public.trip_memory_entries to authenticated
  using (exists (select 1 from public.trips t where t.id=trip_memory_entries.trip_id and t.owner_id=(select auth.uid())))
  with check (exists (select 1 from public.trips t where t.id=trip_memory_entries.trip_id and t.owner_id=(select auth.uid())));
create policy memory_photos_owner on public.trip_memory_photos to authenticated
  using (exists (select 1 from public.trips t where t.id=trip_memory_photos.trip_id and t.owner_id=(select auth.uid())))
  with check (exists (select 1 from public.trips t where t.id=trip_memory_photos.trip_id and t.owner_id=(select auth.uid())));
create policy visit_marks_owner on public.trip_visit_marks to authenticated
  using (exists (select 1 from public.trips t where t.id=trip_visit_marks.trip_id and t.owner_id=(select auth.uid())))
  with check (exists (select 1 from public.trips t where t.id=trip_visit_marks.trip_id and t.owner_id=(select auth.uid())));

revoke all on public.trip_memory_entries, public.trip_memory_photos, public.trip_visit_marks from public, anon, authenticated;
grant select, delete on public.trip_memory_entries to authenticated;
grant insert(id,trip_id,day,title,body,place_id,schedule_id),update(day,title,body,place_id,schedule_id)
  on public.trip_memory_entries to authenticated;
grant select on public.trip_memory_photos to authenticated;
grant insert(id,trip_id,day,title,caption,entry_id,place_id),update(day,title,caption,entry_id,place_id,is_cover,sort_order)
  on public.trip_memory_photos to authenticated;
grant select, insert, update(status) on public.trip_visit_marks to authenticated;
grant select, update, delete on public.trip_memory_photos to service_role;

create function kioku_private.limit_memory_photos() returns trigger
language plpgsql set search_path = '' as $$
declare owner uuid;
begin
  select owner_id into owner from public.trips where id=new.trip_id and owner_id=auth.uid() for no key update;
  if owner is null then raise insufficient_privilege; end if;
  perform pg_advisory_xact_lock(hashtextextended(owner::text, 41031));
  if (select count(*) from public.trip_memory_photos p where p.trip_id=new.trip_id) >= 24
    or (select count(*) from public.trip_memory_photos) >= 120 then
    raise check_violation using message='Memory photo limit reached';
  end if;
  return new;
end;
$$;
revoke all on function kioku_private.limit_memory_photos() from public, anon, authenticated;
create trigger limit_memory_photos before insert on public.trip_memory_photos for each row execute function kioku_private.limit_memory_photos();

create function public.set_trip_visit(p_trip uuid, p_schedule uuid, p_status text) returns void
language sql set search_path = '' as $$
  insert into public.trip_visit_marks(trip_id,schedule_id,status) values (p_trip,p_schedule,p_status)
  on conflict(trip_id,schedule_id) do update set status=excluded.status;
$$;

create function public.organize_memory_photo(p_trip uuid,p_id uuid,p_command text) returns boolean
language plpgsql set search_path = '' as $$
declare selected public.trip_memory_photos;
declare neighbor public.trip_memory_photos;
begin
  perform 1 from public.trips where id=p_trip and owner_id=auth.uid() for no key update;
  if not found then return false; end if;
  select * into selected from public.trip_memory_photos where trip_id=p_trip and id=p_id and phase='ready';
  if not found then return false; end if;
  if p_command='cover' then
    update public.trip_memory_photos set is_cover=false where trip_id=p_trip and is_cover;
    update public.trip_memory_photos set is_cover=true where trip_id=p_trip and id=p_id and phase='ready';
  elsif p_command='earlier' or p_command='later' then
    select * into neighbor from public.trip_memory_photos
      where trip_id=p_trip and phase='ready' and day=selected.day and
      ((p_command='earlier' and sort_order<selected.sort_order) or (p_command='later' and sort_order>selected.sort_order))
      order by case when p_command='earlier' then sort_order end desc, sort_order limit 1;
    if not found then return false; end if;
    update public.trip_memory_photos set sort_order=case id when p_id then neighbor.sort_order else selected.sort_order end
      where trip_id=p_trip and id in (p_id,neighbor.id);
  else
    return false;
  end if;
  return true;
end;
$$;
revoke all on function public.set_trip_visit(uuid,uuid,text), public.organize_memory_photo(uuid,uuid,text) from public, anon, authenticated;
grant execute on function public.set_trip_visit(uuid,uuid,text), public.organize_memory_photo(uuid,uuid,text) to authenticated;

insert into storage.buckets(id,name,public,file_size_limit,allowed_mime_types)
values ('trip-memory','trip-memory',false,524288,array['image/jpeg']);

create policy trip_memory_photo_read on storage.objects for select to authenticated
using (bucket_id='trip-memory' and exists (
  select 1 from public.trip_memory_photos p
  where p.phase='ready' and p.trip_id::text || '/' || p.id::text || '.jpg' = storage.objects.name
));

commit;
