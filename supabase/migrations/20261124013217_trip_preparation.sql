begin;
create table public.trip_preparation (
  id uuid primary key default gen_random_uuid(),
  trip_id uuid not null references public.trips(id) on delete cascade,
  title text not null check (length(btrim(title)) between 1 and 120),
  category text not null check (category in ('entry','flight','stay','transport','tour','online','money','insurance','packing','other')),
  done boolean not null default false,
  due_date date,
  note text check (length(note) <= 600),
  sort_order bigint generated by default as identity,
  source text check (source ~ '^(japan|winter)-[0-9]{1,2}$'),
  unique(trip_id, source),
  unique(trip_id, sort_order) deferrable initially deferred
);
alter table public.trip_preparation enable row level security;
revoke all on public.trip_preparation from public, anon, authenticated;
grant select, delete on public.trip_preparation to authenticated;
grant insert (id,trip_id,title,category,due_date,note,source),
      update (title,category,done,due_date,note,sort_order) on public.trip_preparation to authenticated;
create policy preparation_owner on public.trip_preparation for all to authenticated
  using (exists(select 1 from public.trips t where t.id=trip_id and t.owner_id=(select auth.uid()) and not coalesce((auth.jwt()->>'is_anonymous')::boolean,false)))
  with check (exists(select 1 from public.trips t where t.id=trip_id and t.owner_id=(select auth.uid()) and not coalesce((auth.jwt()->>'is_anonymous')::boolean,false)));

create function public.apply_preparation_template(p_trip uuid,p_items jsonb) returns void
language sql security invoker set search_path='' as $$
  insert into public.trip_preparation(trip_id,title,category,source)
  select p_trip, x.title, x.category, x.source from jsonb_to_recordset(p_items) as x(title text,category text,source text)
  where x.source is not null limit 32
  on conflict (trip_id,source) do nothing;
$$;

create function public.move_preparation(p_trip uuid,p_id uuid,p_direction integer) returns void
language plpgsql security invoker set search_path='' as $$
declare selected public.trip_preparation; adjacent public.trip_preparation;
begin
  if p_direction not in (-1,1) then return; end if;
  perform pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtextextended('preparation:' || p_trip::text,0));
  select * into selected from public.trip_preparation where trip_id=p_trip and id=p_id for update;
  if not found then return; end if;
  select * into adjacent from public.trip_preparation
    where trip_id=p_trip and category=selected.category
    and ((p_direction=1 and sort_order>selected.sort_order) or (p_direction=-1 and sort_order<selected.sort_order))
    order by case when p_direction=1 then sort_order else -sort_order end limit 1 for update;
  if not found then return; end if;
  update public.trip_preparation set sort_order=case when id=p_id then adjacent.sort_order else selected.sort_order end
  where trip_id=p_trip and id in (p_id,adjacent.id);
end;
$$;
revoke all on function public.apply_preparation_template(uuid,jsonb), public.move_preparation(uuid,uuid,integer) from public, anon;
grant execute on function public.apply_preparation_template(uuid,jsonb), public.move_preparation(uuid,uuid,integer) to authenticated;
commit;
