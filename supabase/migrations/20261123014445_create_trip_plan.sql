create policy trip_places_owned on public.trip_places for all to authenticated
  using (exists (select 1 from public.trips where id = trip_places.trip_id and owner_id = (select auth.uid())))
  with check (exists (select 1 from public.trips where id = trip_places.trip_id and owner_id = (select auth.uid())));
create policy itinerary_items_owned on public.itinerary_items for all to authenticated
  using (exists (select 1 from public.trips where id = itinerary_items.trip_id and owner_id = (select auth.uid())))
  with check (exists (select 1 from public.trips where id = itinerary_items.trip_id and owner_id = (select auth.uid())));

create function public.save_itinerary_item(
  p_trip uuid, p_item uuid, p_revision integer, p_trip_version integer, p_fields jsonb
) returns text
language plpgsql security invoker set search_path = '' as $$
declare
  input public.itinerary_items := jsonb_populate_record(null::public.itinerary_items, p_fields);
begin
  -- All app writers lock the parent first, so placements and ranks share one serialization order.
  perform 1 from public.trips where id = p_trip and content_version = p_trip_version for no key update;
  if not found then return 'changed'; end if;
  if p_revision is null then
    insert into public.itinerary_items
      (id, trip_id, title, kind, local_date, time_mode, fixed_local_time, period, place_id, private_note, shared_note)
    values
      (p_item, p_trip, input.title, input.kind, input.local_date, input.time_mode, input.fixed_local_time,
       input.period, input.place_id, input.private_note, input.shared_note)
    on conflict (id) do nothing;
    if found then return 'saved'; end if;
    if exists (select 1 from public.itinerary_items where id = p_item and trip_id = p_trip) then return 'existing'; end if;
    return 'changed';
  end if;

  update public.itinerary_items i
    set title = input.title, kind = input.kind, local_date = input.local_date,
        time_mode = input.time_mode, fixed_local_time = input.fixed_local_time, period = input.period,
        place_id = input.place_id, private_note = input.private_note, shared_note = input.shared_note,
        sort_order = case when (i.local_date, i.time_mode, i.fixed_local_time, i.period)
           is distinct from (input.local_date, input.time_mode, input.fixed_local_time, input.period)
           then nextval('public.itinerary_items_sort_order_seq'::regclass) else i.sort_order end,
        archived_date = case when input.local_date is null then i.archived_date end,
        archived_time_mode = case when input.local_date is null then i.archived_time_mode end,
        archived_fixed_time = case when input.local_date is null then i.archived_fixed_time end,
        archived_period = case when input.local_date is null then i.archived_period end,
        archived_sort_order = case when input.local_date is null then i.archived_sort_order end
    where i.trip_id = p_trip and i.id = p_item and i.revision = p_revision
      and (input.local_date is not null or i.local_date is null);
  if found then return 'saved'; end if;
  return 'changed';
end;
$$;

create function public.swap_itinerary_items(
  p_trip uuid, p_first uuid, p_first_version integer, p_second uuid, p_second_version integer
) returns boolean
language plpgsql security invoker set search_path = '' as $$
declare
  first_item public.itinerary_items;
  second_item public.itinerary_items;
begin
  if p_first = p_second then return false; end if;
  perform 1 from public.trips where id = p_trip for no key update;
  if not found then return false; end if;
  perform 1 from public.itinerary_items where trip_id = p_trip and id in (p_first, p_second) order by id for update;
  select * into first_item from public.itinerary_items where trip_id = p_trip and id = p_first and revision = p_first_version;
  if not found then return false; end if;
  select * into second_item from public.itinerary_items where trip_id = p_trip and id = p_second and revision = p_second_version;
  if not found then return false; end if;
  if (first_item.local_date, first_item.time_mode, first_item.fixed_local_time, first_item.period)
     is distinct from (second_item.local_date, second_item.time_mode, second_item.fixed_local_time, second_item.period)
  then return false; end if;
  update public.itinerary_items set sort_order = case when id = p_first then second_item.sort_order else first_item.sort_order end
    where trip_id = p_trip and id in (p_first, p_second);
  return true;
end;
$$;

create function public.place_itinerary_item(
  p_trip uuid, p_item uuid, p_revision integer, p_command text, p_date date, p_trip_version integer
) returns boolean
language plpgsql security invoker set search_path = '' as $$
declare
  item public.itinerary_items;
  restore_order bigint;
begin
  perform 1 from public.trips where id = p_trip and content_version = p_trip_version for no key update;
  if not found then return false; end if;
  select * into item from public.itinerary_items where trip_id = p_trip and id = p_item and revision = p_revision for update;
  if not found then return false; end if;

  if p_command = 'archive' and item.local_date is not null then
    update public.itinerary_items set archived_date = local_date, archived_time_mode = time_mode,
      archived_fixed_time = fixed_local_time, archived_period = period, archived_sort_order = sort_order,
      local_date = null, time_mode = 'UNSCHEDULED', fixed_local_time = null, period = null, sort_order = default
      where id = p_item and trip_id = p_trip;
  elsif p_command = 'restore' and item.archived_date is not null then
    restore_order := item.archived_sort_order;
    -- Preserve intervening edits: if the old position is occupied, append within the target group.
    if exists (
      select 1 from public.itinerary_items i where i.trip_id = p_trip and i.sort_order = restore_order
        and (i.local_date, i.time_mode, i.fixed_local_time, i.period) is not distinct from
            (item.archived_date, item.archived_time_mode, item.archived_fixed_time, item.archived_period)
    ) then
      restore_order := nextval('public.itinerary_items_sort_order_seq'::regclass);
    end if;
    update public.itinerary_items set local_date = archived_date, time_mode = archived_time_mode,
      fixed_local_time = archived_fixed_time, period = archived_period, sort_order = restore_order,
      archived_date = null, archived_time_mode = null, archived_fixed_time = null, archived_period = null, archived_sort_order = null
      where id = p_item and trip_id = p_trip;
  elsif p_command = 'move' and p_date is not null and p_date is distinct from item.local_date then
    update public.itinerary_items set local_date = p_date, sort_order = default,
      archived_date = null, archived_time_mode = null, archived_fixed_time = null, archived_period = null, archived_sort_order = null
      where id = p_item and trip_id = p_trip;
  elsif p_command = 'delete' then
    delete from public.itinerary_items where id = p_item and trip_id = p_trip;
  else
    return false;
  end if;
  return true;
end;
$$;

create function public.update_trip_period(
  p_trip uuid, p_version integer, p_fields jsonb, p_expected jsonb
) returns jsonb
language plpgsql security invoker set search_path = '' as $$
declare
  original public.trips;
  input public.trips := jsonb_populate_record(null::public.trips, p_fields);
  impact jsonb;
begin
  select * into original from public.trips where id = p_trip and content_version = p_version for no key update;
  if not found then return jsonb_build_object('status', 'changed'); end if;

  -- Writers share the parent lock, so the preview cannot go stale between comparison and save.
  with classified as (
    select local_date,
      case when original.start_date is null then 'NO_RANGE'
           when local_date between original.start_date and original.end_date then 'DAY'
           else 'OUTSIDE' end as old_group,
      case when input.start_date is null then 'NO_RANGE'
           when local_date between input.start_date and input.end_date then 'DAY'
           else 'OUTSIDE' end as new_group
    from public.itinerary_items where trip_id = p_trip and local_date is not null
  ), affected as (
    select local_date, count(*) as item_count, new_group
    from classified where old_group <> new_group group by local_date, new_group
  )
  select coalesce(jsonb_agg(jsonb_build_object('date', to_char(local_date, 'YYYY-MM-DD'), 'count', item_count,
    'group', new_group) order by local_date), '[]'::jsonb) into impact from affected;

  if impact <> '[]'::jsonb and impact is distinct from p_expected then
    return jsonb_build_object('status', 'preview', 'entries', impact);
  end if;
  update public.trips set title = input.title, destination_label = input.destination_label,
    start_date = input.start_date, end_date = input.end_date, traveler_count = input.traveler_count
    where id = p_trip and content_version = p_version;
  if not found then return jsonb_build_object('status', 'changed'); end if;
  return jsonb_build_object('status', 'saved');
end;
$$;

revoke execute on function public.update_trip_period(uuid, integer, jsonb, jsonb) from public, anon, authenticated;
grant execute on function public.update_trip_period(uuid, integer, jsonb, jsonb) to authenticated;

