begin;

create table public.trip_places (
  id uuid primary key default gen_random_uuid(),
  trip_id uuid not null references public.trips (id) on delete cascade,
  name text not null check (char_length(name) <= 100 and name ~ '[^[:space:]]'),
  address text check (char_length(address) <= 240),
  latitude double precision,
  longitude double precision,
  notes text check (char_length(notes) <= 1500),
  content_version integer not null default 1 check (content_version >= 1),
  updated_at timestamptz not null default now(),
  unique (trip_id, id),
  constraint trip_places_coordinates check (
    (latitude is null and longitude is null)
    or (latitude is not null and longitude is not null and latitude between -90 and 90 and longitude between -180 and 180)
  )
);

create table public.itinerary_items (
  id uuid primary key default gen_random_uuid(),
  trip_id uuid not null references public.trips (id) on delete cascade,
  kind text not null default 'NOTE' check (kind in ('PLACE', 'MOVE', 'NOTE', 'BOOKING_REF')),
  title text not null check (char_length(title) <= 100 and title ~ '[^[:space:]]'),
  local_date date check (local_date between date '0001-01-01' and date '9999-12-31'),
  time_mode text not null default 'UNSCHEDULED',
  fixed_local_time time(0) check (fixed_local_time < time '24:00' and extract(second from fixed_local_time) = 0),
  period text,
  sort_order bigint generated by default as identity check (sort_order > 0),
  place_id uuid,
  booking_id uuid,
  private_note text check (char_length(private_note) <= 1500),
  shared_note text check (char_length(shared_note) <= 1500),
  revision integer not null default 1 check (revision >= 1),
  updated_at timestamptz not null default now(),
  archived_date date check (archived_date between date '0001-01-01' and date '9999-12-31'),
  archived_time_mode text,
  archived_fixed_time time(0) check (archived_fixed_time < time '24:00' and extract(second from archived_fixed_time) = 0),
  archived_period text,
  archived_sort_order bigint,
  foreign key (trip_id, place_id) references public.trip_places (trip_id, id),
  -- M4 replaces this guard with the same-trip booking FK and write grants.
  constraint itinerary_booking_pending check (booking_id is null and kind <> 'BOOKING_REF'),
  constraint itinerary_time_mode check (
    (time_mode = 'UNSCHEDULED' and fixed_local_time is null and period is null)
    or (time_mode = 'FIXED' and local_date is not null and fixed_local_time is not null and period is null)
    or (time_mode = 'PERIOD' and local_date is not null and fixed_local_time is null
        and period is not null and period in ('MORNING','AFTERNOON','EVENING'))
  ),
  constraint itinerary_archive_snapshot check (
    (archived_date is null and archived_time_mode is null and archived_fixed_time is null
      and archived_period is null and archived_sort_order is null)
    or (archived_date is not null and local_date is null and archived_time_mode is not null
      and archived_sort_order is not null and archived_sort_order > 0
      and ((archived_time_mode = 'UNSCHEDULED' and archived_fixed_time is null and archived_period is null)
        or (archived_time_mode = 'FIXED' and archived_fixed_time is not null and archived_period is null)
        or (archived_time_mode = 'PERIOD' and archived_fixed_time is null
            and archived_period is not null and archived_period in ('MORNING','AFTERNOON','EVENING'))))
  )
);

create index itinerary_items_order_idx on public.itinerary_items (trip_id, local_date, sort_order, id);
create index itinerary_items_place_idx on public.itinerary_items (trip_id, place_id);

create function public.set_itinerary_revision() returns trigger
language plpgsql set search_path = '' as $$
begin
  new.revision := old.revision + 1;
  new.updated_at := statement_timestamp();
  return new;
end;
$$;

revoke execute on function public.set_itinerary_revision() from public, anon, authenticated;

create trigger trip_places_set_revision before update on public.trip_places
  for each row execute function public.set_trip_revision();
create trigger itinerary_items_set_revision before update on public.itinerary_items
  for each row execute function public.set_itinerary_revision();

revoke all on public.trip_places, public.itinerary_items from public, anon, authenticated;
grant select on public.trip_places, public.itinerary_items to authenticated;
grant insert (id, trip_id, name, address, latitude, longitude, notes),
  update (name, address, latitude, longitude, notes) on public.trip_places to authenticated;
grant insert (id, trip_id, title, kind, local_date, time_mode, fixed_local_time, period, place_id, private_note, shared_note),
  update (title, kind, local_date, time_mode, fixed_local_time, period, place_id, private_note, shared_note, sort_order,
    archived_date, archived_time_mode, archived_fixed_time, archived_period, archived_sort_order),
  delete on public.itinerary_items to authenticated;
revoke all on sequence public.itinerary_items_sort_order_seq from public, anon, authenticated;
grant usage on sequence public.itinerary_items_sort_order_seq to authenticated;

alter table public.trip_places enable row level security;
